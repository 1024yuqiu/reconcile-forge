import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('../shots', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const errors = [], evidence = [];
try {
  for (const width of [1440, 375]) {
    console.log(`Checking ${width}px viewport`);
    const context = await browser.newContext({ viewport: { width, height: 960 }, acceptDownloads: true });
    context.setDefaultTimeout(15000);
    const page = await context.newPage();
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('http://127.0.0.1:4173/');
    await page.getByRole('button', { name: 'Run reconciliation', exact: true }).waitFor();
    console.log(`${width}px sources loaded`);
    await page.screenshot({ path: `../shots/setup-${width}.png`, fullPage: true });
    await page.getByRole('button', { name: 'Save template', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Template saved' }).waitFor();
    await page.getByRole('button', { name: 'Run reconciliation', exact: true }).click();
    await page.getByText('Every difference, accounted for.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Export XLSX' }).waitFor({ state: 'visible' });
    await page.waitForFunction(() => !document.querySelector('.section-title button').disabled, null, { timeout: 15000, polling: 100 });
    await page.locator('.results').scrollIntoViewIfNeeded();
    // Capture result section at its top, independently of the taller mapping area.
    await page.evaluate(() => document.querySelector('.results').scrollIntoView({ block: 'start' }));
    await page.screenshot({ path: `../shots/results-${width}.png`, fullPage: false });
    const counts = await page.locator('.metric strong').allTextContents();
    assert.deepEqual(counts, ['270', '18', '10', '10', '1']);
    await page.getByRole('combobox', { name: 'Result category', exact: true }).selectOption('mismatch');
    assert.equal(await page.locator('tbody tr').count(), 18);
    await page.getByRole('searchbox').fill('ap-0001');
    assert.equal(await page.locator('tbody tr').count(), 1);
    assert.equal(await page.locator('.diff-cell').count(), 2);
    await page.getByRole('searchbox').fill('');
    await page.getByRole('combobox', { name: 'Result category', exact: true }).selectOption('duplicate');
    assert.equal(await page.locator('tbody tr').count(), 1);
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export XLSX' }).click();
    const download = await downloadPromise;
    assert.equal(download.suggestedFilename(), 'reconciliation.xlsx');
    await download.saveAs(`../shots/export-${width}.xlsx`);
    await page.getByLabel('Issue type ID', { exact: true }).fill('10001');
    await page.getByRole('button', { name: 'Review issue creation' }).click();
    await page.getByRole('region', { name: 'Confirm issue creation' }).waitFor();
    assert.equal(await page.getByRole('status').count(), 0);
    await page.getByRole('button', { name: 'Confirm creation', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Created: DEMO-' }).waitFor();
    // Repeat from offset 0 by rerunning the same input, then create: all twenty are reused.
    await page.getByRole('button', { name: 'Run reconciliation', exact: true }).click();
    await page.getByRole('button', { name: 'Review issue creation' }).waitFor();
    await page.getByRole('button', { name: 'Review issue creation' }).click();
    await page.getByRole('button', { name: 'Confirm creation', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Created: none. Reused: DEMO-' }).waitFor();
    await page.getByRole('button', { name: /Run history/ }).click();
    assert.equal(await page.locator('.history').count(), 2);
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    assert.equal(overflow, false, `Page overflow at ${width}`);
    evidence.push({ width, counts, mismatchRows: 18, searchedRows: 1, duplicateGroups: 1, exported: true, confirmation: true, rerunReuses: true, historyRuns: 2, pageOverflow: overflow });
    await context.close();
    console.log(`${width}px workflow passed`);
  }
  assert.deepEqual(errors, []);
  const localContext = await browser.newContext();
  console.log('Checking local uploads and JQL');
  localContext.setDefaultTimeout(15000);
  const local = await localContext.newPage();
  local.on('pageerror', e => errors.push(e.message));
  await local.goto('http://127.0.0.1:4173/');
  await local.getByRole('button', { name: 'Run reconciliation', exact: true }).waitFor();
  await local.locator('input[type=file]').nth(0).setInputFiles('../samples/ap-ledger.csv');
  await local.getByText('ap-ledger.csv', { exact: true }).waitFor();
  await local.locator('input[type=file]').nth(1).setInputFiles('../samples/bank-statement.xlsx');
  await local.locator('.file-meta strong').filter({ hasText: /^bank-statement\.xlsx$/ }).waitFor();
  await local.getByRole('button', { name: 'Run reconciliation', exact: true }).waitFor();
  await local.getByRole('button', { name: 'Run reconciliation', exact: true }).click();
  await local.getByRole('status').filter({ hasText: 'Local file comparison complete' }).waitFor();
  assert.deepEqual(await local.locator('.metric strong').allTextContents(), ['270', '18', '10', '10', '1']);
  evidence.push({ path: 'preview CSV + XLSX upload and real Web Worker', passed: true });
  await local.getByRole('combobox', { name: 'Source B', exact: true }).selectOption('jql');
  await local.getByLabel('JQL query', { exact: true }).fill('project = DEMO');
  await local.getByRole('button', { name: 'Load selected sources' }).click();
  await local.getByText('JQL results', { exact: true }).waitFor();
  await local.getByRole('combobox', { name: 'amount column A', exact: true }).selectOption('');
  await local.getByRole('combobox', { name: 'date column A', exact: true }).selectOption('');
  await local.getByRole('button', { name: 'Run reconciliation', exact: true }).click();
  await local.getByText('Every difference, accounted for.', { exact: true }).waitFor();
  assert.equal((await local.locator('.metric strong').allTextContents())[0], '1');
  evidence.push({ path: 'attachment A + JQL B, key-only mapping', passed: true });
  await localContext.close();
  assert.deepEqual(errors, []);
  await writeFile('../logs/ui-check.json', JSON.stringify({ passed: true, browser: 'headless Microsoft Edge / Playwright', errors, evidence }, null, 2));
  console.log(JSON.stringify({ passed: true, evidence }, null, 2));
} finally { await browser.close(); }
